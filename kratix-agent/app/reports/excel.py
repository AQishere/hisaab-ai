"""Excel writer: a Summary sheet with the key figures, then one sheet per table."""

from datetime import date
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from .catalog import DATE, INT, KG, PERCENT, PKR, QTY, ReportData, Table, day_text

NUMBER_FORMATS = {PKR: '#,##0;-#,##0', QTY: '#,##0.##', KG: '#,##0.##', INT: '0', PERCENT: '0.0"%"', DATE: 'dd mmm yyyy'}
HEADER_FILL = PatternFill("solid", fgColor="1F3A5F")
HEADER_FONT = Font(bold=True, color="FFFFFF")
TITLE_FONT = Font(bold=True, size=14)
MUTED_FONT = Font(italic=True, color="666666")


def _cell_value(value, fmt):
    if fmt == DATE and isinstance(value, str) and value:
        return date.fromisoformat(value[:10])
    return value


def _fit_columns(sheet, widths: dict[int, int]) -> None:
    for index, width in widths.items():
        sheet.column_dimensions[get_column_letter(index)].width = min(max(width + 2, 10), 50)


def _write_table(sheet, table: Table, first_row: int) -> None:
    widths: dict[int, int] = {}
    for col, column in enumerate(table.columns, start=1):
        cell = sheet.cell(row=first_row, column=col, value=column.header)
        cell.font, cell.fill = HEADER_FONT, HEADER_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        widths[col] = len(column.header)
    for offset, row in enumerate(table.rows, start=1):
        for col, column in enumerate(table.columns, start=1):
            value = _cell_value(row.get(column.key), column.fmt)
            cell = sheet.cell(row=first_row + offset, column=col, value=value)
            if column.fmt in NUMBER_FORMATS:
                cell.number_format = NUMBER_FORMATS[column.fmt]
            shown = f"{value:,.2f}" if isinstance(value, float) else str(value if value is not None else "")
            widths[col] = max(widths[col], len(shown))
    if not table.rows:
        sheet.cell(row=first_row + 1, column=1, value=table.empty_text).font = MUTED_FONT
    sheet.freeze_panes = sheet.cell(row=first_row + 1, column=1)
    _fit_columns(sheet, widths)


def write_excel(report: ReportData, path: Path, company: str, generated_for: str, generated_on: date) -> None:
    book = Workbook()
    summary = book.active
    summary.title = "Summary"
    summary["A1"] = f"{company} - {report.title}"
    summary["A1"].font = TITLE_FONT
    summary["A2"] = report.period
    summary["A3"] = f"Generated by Hisaab Assistant on {day_text(generated_on)} for {generated_for}"
    summary["A3"].font = MUTED_FONT
    for offset, figure in enumerate(report.figures, start=5):
        summary.cell(row=offset, column=1, value=figure.label).font = Font(bold=True)
        cell = summary.cell(row=offset, column=2, value=figure.value)
        if figure.fmt in NUMBER_FORMATS:
            cell.number_format = NUMBER_FORMATS[figure.fmt]
    summary.column_dimensions["A"].width = 28
    summary.column_dimensions["B"].width = 20

    for table in report.tables:
        sheet = book.create_sheet(table.name[:31])
        _write_table(sheet, table, first_row=1)
    book.save(path)
